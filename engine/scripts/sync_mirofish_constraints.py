"""Pin the engine's shared dependencies to the versions MiroFish upstream is tested with.

Reads engine/mirofish/backend/uv.lock and rewrites the generated block of
[tool.uv] constraint-dependencies in engine/pyproject.toml. Run it after every
`git subtree pull` of MiroFish, then `uv lock && uv sync`.

Usage: uv run python scripts/sync_mirofish_constraints.py
"""

from __future__ import annotations

import re
import tomllib
from pathlib import Path

ENGINE = Path(__file__).resolve().parent.parent
LOCK = ENGINE / "mirofish" / "backend" / "uv.lock"
PYPROJECT = ENGINE / "pyproject.toml"

BEGIN = "# BEGIN generated by scripts/sync_mirofish_constraints.py"
END = "# END generated"

# Packages Hyvo deliberately lets float away from the MiroFish lock.
UNPINNED: set[str] = {"mirofish-backend"}


def main() -> None:
    lock = tomllib.loads(LOCK.read_text(encoding="utf-8"))
    pins = sorted(
        {
            (pkg["name"], pkg["version"])
            for pkg in lock["package"]
            if pkg["name"] not in UNPINNED and "version" in pkg and pkg.get("source", {}).get("registry")
        }
    )
    lines = "\n".join(f'    "{name}=={version}",' for name, version in pins)
    block = f"{BEGIN}\nconstraint-dependencies = [\n{lines}\n]\n{END}"

    text = PYPROJECT.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
    if pattern.search(text):
        text = pattern.sub(lambda _: block, text)
    else:
        text = text.rstrip() + "\n\n[tool.uv]\n" + block + "\n"
    PYPROJECT.write_text(text, encoding="utf-8")
    print(f"pinned {len(pins)} packages from {LOCK.relative_to(ENGINE)}")


if __name__ == "__main__":
    main()
